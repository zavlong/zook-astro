export type SectorExportFormatType =
  | 'stargen-sector'
  | 'stellaris-static-galaxy'
  | 'spaceengine-sector';

export interface SectorExportBundle {
  format: 'zook-sector-v1';
  exportedAt: string;
  config: SectorHexConfig;
  gridData: SectorHexGridData;
  empires: SectorEmpire[];
  activeEmpireId: string | null;
}

export interface ParsedSectorImportResult {
  sourceFormat: 'stargen-sector' | 'stellaris-static-galaxy';
  config: SectorHexConfig;
  gridData: SectorHexGridData;
  empires?: SectorEmpire[];
  activeEmpireId?: string | null;
}

function classifySpectralCatFromType(spectralType: string, isRemnant: boolean): SpectralCategory {
  if (isRemnant) return 'remnant';
  const s = (spectralType || '').trim().toUpperCase();
  if (s.startsWith('O') || s.startsWith('B')) return 'ob';
  if (s.startsWith('A') || s.startsWith('F')) return 'af';
  if (s.startsWith('G')) return 'g';
  return 'km';
}

/**
 * Exports a Sector in native Stargen / Zook Astro JSON format (.json).
 */
export function exportSectorAsZookJson(
  gridData: SectorHexGridData,
  empires: SectorEmpire[] = [],
  activeEmpireId: string | null = null
): string {
  const bundle: SectorExportBundle = {
    format: 'zook-sector-v1',
    exportedAt: new Date().toISOString(),
    config: gridData.config,
    gridData,
    empires,
    activeEmpireId,
  };
  return JSON.stringify(bundle, null, 2);
}

/**
 * Exports an individual Sector in Stellaris Static Galaxy Scenario format (`map/setup_scenarios/*.txt`),
 * with all unused Zook Astro / Stargen sector and astrophysical properties commented out with `#`.
 * Optionally appends the full `solar_system_initializer` definitions at the bottom.
 */
export function exportSectorAsStellarisStaticGalaxy(
  gridData: SectorHexGridData,
  empires: SectorEmpire[] = [],
  includeSystemInitializers: boolean = false
): string {
  const cfg = gridData.config;
  const sectorName = cfg.name || (cfg.coord ? `Sector ${cfg.coord}` : `Sector-${cfg.seed}`);
  const systems = gridData.systems || [];
  const hyperlanes = gridData.hyperlanes || [];

  // Map system.id -> numeric Stellaris index ("0", "1", "2", ...)
  const sysIdToIndex = new Map<string, number>();
  systems.forEach((sys, idx) => {
    sysIdToIndex.set(sys.id, idx);
  });

  // Map system.id -> owning Empire
  const empireBySysId = new Map<string, SectorEmpire>();
  empires.forEach((emp) => {
    (emp.claimedSystemIds || []).forEach((sid) => {
      empireBySysId.set(sid, emp);
    });
  });

  // Coordinate scaling from Sector SVG space (center ~1200,1200, radius ~1120) to Stellaris [-450, 450]
  const cx = gridData.hexCenterX || 1200;
  const cy = gridData.hexCenterY || 1200;
  const hexR = Math.max(200, gridData.hexRadius || 1120);
  const stellarisRadius = 450;
  const scaleToStellaris = stellarisRadius / hexR;

  const maxEmpires = Math.max(1, Math.min(30, empires.length > 0 ? empires.length * 2 : Math.max(4, Math.round(systems.length / 12))));
  const defaultEmpires = Math.max(1, empires.length > 0 ? empires.length : Math.min(8, Math.max(1, Math.round(systems.length / 20))));

  const out: string[] = [];
  out.push(`# ============================================================================`);
  out.push(`# Stellaris Static Galaxy Scenario — Generated by Zook Astro`);
  out.push(`# Sector: "${sectorName}" ${cfg.coord ? `(Coord ${cfg.coord})` : ''} | Seed #${cfg.seed}`);
  out.push(`# Place in: map/setup_scenarios/${sectorName.toLowerCase().replace(/[^a-z0-9]+/g, '_')}.txt`);
  out.push(`# --- Unused Zook Astro Sector Telemetry (Preserved for Round-Trip Import) ---`);
  out.push(`# sector_seed = ${cfg.seed}`);
  if (cfg.coord) out.push(`# sector_coord = "${cfg.coord}"`);
  out.push(`# columns = ${cfg.columns}`);
  out.push(`# rows = ${cfg.rows}`);
  out.push(`# density = ${cfg.density}`);
  out.push(`# mean_age = ${cfg.meanAge}`);
  out.push(`# age_sigma = ${cfg.ageSigma}`);
  if (cfg.ageRange !== undefined) out.push(`# age_range = ${cfg.ageRange}`);
  if (cfg.ageDistribution) out.push(`# age_distribution = "${cfg.ageDistribution}"`);
  out.push(`# metallicity_mean = ${cfg.metallicityMean}`);
  out.push(`# metallicity_sigma = ${cfg.metallicitySigma}`);
  out.push(`# has_nebula = ${gridData.hasNebula ? 'yes' : 'no'}`);
  out.push(`# integrated_color_hex = "${gridData.integratedColorHex}"`);
  out.push(`# sector_dimensions_px = { width = ${gridData.sectorWidth} height = ${gridData.sectorHeight} center_x = ${cx} center_y = ${cy} hex_radius = ${hexR} }`);
  out.push(`# sector_dimensions_pc = { width = ${gridData.parsecWidth} height = ${gridData.parsecHeight} }`);
  out.push(`# sector_stats = { total_hexes = ${gridData.stats.totalHexes} occupied_hexes = ${gridData.stats.occupiedHexes} occupancy_pct = ${gridData.stats.occupancyPct} total_stars = ${gridData.stats.totalStars} hyperlanes = ${gridData.stats.hyperlaneCount} ob = ${gridData.stats.obCount} af = ${gridData.stats.afCount} g = ${gridData.stats.gCount} km = ${gridData.stats.kmCount} remnants = ${gridData.stats.remnantCount} multi_star = ${gridData.stats.multipleSystemCount} habitable = ${gridData.stats.habitableCount} }`);
  if (empires.length > 0) {
    out.push(`# --- Sector Civilizations & Empires (${empires.length}) ---`);
    empires.forEach((emp) => {
      out.push(
        `# zook_empire = { id = "${emp.id}" name = "${emp.name}" color = "${emp.color}" phenotype = "${emp.phenotype?.name || 'Unknown'}" homeworld_sys = "${emp.homeworldSystemId}" homeworld_name = "${emp.homeworldName}" claimed_systems = ${emp.claimedSystemIds.length} }`
      );
    });
  }
  out.push(`# ============================================================================`);
  out.push(``);

  out.push(`static_galaxy_scenario = {`);
  out.push(`\tname = "${sectorName}"`);
  out.push(`\tpriority = 0`);
  out.push(`\tdefault = no`);
  out.push(`\tnum_empires = { min = 0 max = ${maxEmpires} }`);
  out.push(`\tnum_empire_default = ${defaultEmpires}`);
  out.push(`\tfallen_empire_default = 0`);
  out.push(`\tfallen_empire_max = 2`);
  out.push(`\tmarauder_empire_default = 0`);
  out.push(`\tmarauder_empire_max = 1`);
  out.push(`\tadvanced_empire_default = 0`);
  out.push(`\tcolonizable_planet_odds = 1.0`);
  out.push(`\tprimitive_odds = 1.0`);
  out.push(`\tcrisis_strength = 1.0`);
  out.push(`\textra_crisis_strength = { 10 25 }`);
  out.push(`\tsupports_shape = elliptical`);
  out.push(`\trandom_hyperlanes = no`);
  out.push(``);

  // Star Systems
  out.push(`\t# ------------------------------------------------------------------------`);
  out.push(`\t# Star Systems (${systems.length})`);
  out.push(`\t# ------------------------------------------------------------------------`);
  systems.forEach((sys, idx) => {
    const stX = +((sys.x - cx) * scaleToStellaris).toFixed(2);
    const stY = +((sys.y - cy) * scaleToStellaris).toFixed(2);
    const safeInitId =
      (sys.name || sys.id || `sys_${idx}`).toLowerCase().replace(/[^a-z0-9]+/g, '_') + '_initializer';
    const ownerEmp = empireBySysId.get(sys.id);
    const isCapital = ownerEmp != null && ownerEmp.homeworldSystemId === sys.id;
    const isSpawnCandidate = isCapital || (empires.length === 0 && sys.candidateHabitable);

    out.push(`\tsystem = {`);
    out.push(`\t\tid = "${idx}"`);
    out.push(`\t\tname = "${sys.name}"`);
    out.push(`\t\tposition = {`);
    out.push(`\t\t\tx = ${stX}`);
    out.push(`\t\t\ty = ${stY}`);
    out.push(`\t\t}`);
    if (includeSystemInitializers) {
      out.push(`\t\tinitializer = ${safeInitId}`);
    } else {
      out.push(`\t\t# initializer = ${safeInitId}`);
    }
    if (isSpawnCandidate) {
      out.push(`\t\tspawn_weight = { base = ${isCapital ? 100 : 25} }`);
      if (isCapital) {
        out.push(`\t\tflags = { empire_home_system }`);
      }
    } else {
      out.push(`\t\t# spawn_weight = { base = 0 }`);
    }

    // Commented-out Zook Astro / Stargen properties not natively read by Stellaris static_galaxy_scenario
    out.push(`\t\t# --- Unused Stargen Sector & Astrophysical Data ---`);
    out.push(`\t\t# zook_id = "${sys.id}"`);
    out.push(`\t\t# coord = "${sys.coord}"`);
    out.push(`\t\t# col = ${sys.col}`);
    out.push(`\t\t# row = ${sys.row}`);
    out.push(`\t\t# pixel_pos = { x = ${sys.x} y = ${sys.y} }`);
    out.push(`\t\t# parsec_pos = { x = ${sys.parsecX} y = ${sys.parsecY} }`);
    out.push(`\t\t# influence_radius = ${sys.influenceRadius}`);
    out.push(`\t\t# primary_class = "${sys.primaryClass}"`);
    out.push(`\t\t# spectral_cat = "${sys.spectralCat}"`);
    out.push(`\t\t# sys_mass_sol = ${sys.mass}`);
    out.push(`\t\t# primary_mass_sol = ${sys.primaryMass}`);
    out.push(`\t\t# age_gyr = ${sys.age}`);
    out.push(`\t\t# metallicity_feh = ${sys.metallicity}`);
    out.push(`\t\t# teff_k = ${Math.round(sys.teff)}`);
    out.push(`\t\t# lum_lsun = ${sys.lumLsun}`);
    out.push(`\t\t# color_hex = "${sys.colorHex}"`);
    out.push(`\t\t# is_remnant = ${sys.isRemnant ? 'yes' : 'no'}`);
    if (sys.remnantType) out.push(`\t\t# remnant_type = "${sys.remnantType}"`);
    out.push(`\t\t# n_stars = ${sys.nStars}`);
    out.push(`\t\t# arch_name = "${sys.archName}"`);
    out.push(`\t\t# planet_count = ${sys.planetCount}`);
    out.push(`\t\t# belt_count = ${sys.beltCount}`);
    out.push(`\t\t# candidate_habitable = ${sys.candidateHabitable ? 'yes' : 'no'}`);
    if (sys.habitableWorldCount) out.push(`\t\t# habitable_worlds = ${sys.habitableWorldCount}`);
    if (sys.habitableTypes && sys.habitableTypes.length > 0) {
      out.push(`\t\t# habitable_types = "${sys.habitableTypes.join(', ')}"`);
    }
    if (ownerEmp) {
      out.push(`\t\t# empire_owner = "${ownerEmp.name}" (${isCapital ? 'Capital' : 'Claimed'})`);
    }
    out.push(`\t}`);
    out.push(``);
  });

  // Hyperlanes
  out.push(`\t# ------------------------------------------------------------------------`);
  out.push(`\t# Hyperlane Network (${hyperlanes.length} routes)`);
  out.push(`\t# ------------------------------------------------------------------------`);
  hyperlanes.forEach((lane) => {
    const fromIdx = sysIdToIndex.get(lane.sourceId);
    const toIdx = sysIdToIndex.get(lane.targetId);
    if (!lane.isEdgeLane && fromIdx !== undefined && toIdx !== undefined) {
      out.push(
        `\tadd_hyperlane = { from = "${fromIdx}" to = "${toIdx}" } # ${lane.sourceCoord} <-> ${lane.targetCoord} (${lane.lengthLy} ly)`
      );
    } else if (fromIdx !== undefined) {
      const borderX = +((lane.x2 - cx) * scaleToStellaris).toFixed(2);
      const borderY = +((lane.y2 - cy) * scaleToStellaris).toFixed(2);
      out.push(
        `\t# edge_hyperlane = { from = "${fromIdx}" to_border = { x = ${borderX} y = ${borderY} } length_ly = ${lane.lengthLy} }`
      );
    }
  });
  out.push(``);

  // Nebula
  if (gridData.nebula || gridData.hasNebula) {
    const neb = gridData.nebula;
    out.push(`\t# ------------------------------------------------------------------------`);
    out.push(`\t# Sector Emission Nebula`);
    out.push(`\t# ------------------------------------------------------------------------`);
    out.push(`\tnebula = {`);
    out.push(`\t\tname = "${neb?.name || `${sectorName} Nebula`}"`);
    const avgBlobX =
      neb && neb.blobs.length > 0
        ? neb.blobs.reduce((s, b) => s + b.cx, 0) / neb.blobs.length
        : cx;
    const avgBlobY =
      neb && neb.blobs.length > 0
        ? neb.blobs.reduce((s, b) => s + b.cy, 0) / neb.blobs.length
        : cy;
    out.push(`\t\tposition = {`);
    out.push(`\t\t\tx = ${+((avgBlobX - cx) * scaleToStellaris).toFixed(2)}`);
    out.push(`\t\t\ty = ${+((avgBlobY - cy) * scaleToStellaris).toFixed(2)}`);
    out.push(`\t\t}`);
    out.push(`\t\tradius = 160`);
    if (neb) {
      out.push(`\t\t# nebula_type = "${neb.type}"`);
      out.push(`\t\t# description = "${neb.description}"`);
      out.push(`\t\t# blob_count = ${neb.blobs.length}`);
      out.push(`\t\t# dust_lane_count = ${neb.dustLanes.length}`);
    }
    out.push(`\t}`);
  } else {
    out.push(`\t# No active emission nebula in this sector`);
    out.push(`\t# nebula = { name = "${sectorName} Nebula" position = { x = 0 y = 0 } radius = 100 }`);
  }

  out.push(`}`);

  // Optional: Append full solar_system_initializer blocks for every system in the sector
  if (includeSystemInitializers && systems.length > 0) {
    out.push(``);
    out.push(`# ============================================================================`);
    out.push(`# SOLAR SYSTEM INITIALIZERS FOR SECTOR "${sectorName.toUpperCase()}"`);
    out.push(`# (Place in: common/solar_system_initializers/${sectorName.toLowerCase().replace(/[^a-z0-9]+/g, '_')}_initializers.txt)`);
    out.push(`# ============================================================================`);
    out.push(``);
    systems.forEach((sys, idx) => {
      if (!sys.sysResult) return;
      const sysClone = {
        ...sys.sysResult,
        step1: {
          ...sys.sysResult.step1,
          name: `${sys.name}_${sys.coord || idx}`,
        },
      };
      out.push(exportSystemAsStellarisInitializer(sysClone));
      out.push(``);
    });
  }

  return out.join('\n');
}

/**
 * Exports all star systems in an individual Sector as a unified SpaceEngine (.sc) catalog file,
 * with all unused sector & Stargen data commented out (`// ...`).
 */
export function exportSectorAsSpaceEngineSc(gridData: SectorHexGridData): string {
  const cfg = gridData.config;
  const sectorName = cfg.name || (cfg.coord ? `Sector ${cfg.coord}` : `Sector-${cfg.seed}`);
  const out: string[] = [];
  out.push(`// ============================================================================`);
  out.push(`// SpaceEngine (.sc) Sector Catalog Export — Generated by Zook Astro`);
  out.push(`// Sector: "${sectorName}" ${cfg.coord ? `(Coord ${cfg.coord})` : ''} | Seed #${cfg.seed}`);
  out.push(`// Grid: ${cfg.columns}x${cfg.rows} (${gridData.parsecWidth}x${gridData.parsecHeight} pc) | Systems: ${gridData.systems.length}`);
  out.push(`// Mean Age: ${cfg.meanAge} Gyr | Mean [Fe/H]: ${cfg.metallicityMean} dex | Integrated Light: ${gridData.integratedColorHex}`);
  out.push(`// ============================================================================`);
  out.push(``);

  gridData.systems.forEach((sys, idx) => {
    out.push(`// ############################################################################`);
    out.push(`// SECTOR SYSTEM #${idx + 1}: "${sys.name}" (Hex Coord ${sys.coord} | ${sys.parsecX} pc, ${sys.parsecY} pc)`);
    out.push(`// Zook ID: ${sys.id} | Primary: ${sys.primaryClass} | Planets: ${sys.planetCount} | Habitable: ${sys.candidateHabitable}`);
    out.push(`// ############################################################################`);
    if (sys.sysResult) {
      const sysClone = {
        ...sys.sysResult,
        step1: {
          ...sys.sysResult.step1,
          name: sys.name || sys.id,
        },
      };
      out.push(exportSystemAsSpaceEngineSc(sysClone));
    }
    out.push(``);
  });

  return out.join('\n');
}

/**
 * Parses an imported Sector file — supports BOTH:
 * 1. Stargen / Zook Sector JSON (`.json`)
 * 2. Stellaris Static Galaxy Scenario format (`static_galaxy_scenario = { ... }` in `.txt`)
 */
export function parseImportedSectorData(rawText: string): ParsedSectorImportResult {
  const trimmed = rawText.trim();
  if (!trimmed) {
    throw new Error('Import text is empty.');
  }

  // Case 1: JSON Format (Zook Sector Bundle, SectorHexGridData, or SectorHexConfig)
  if (trimmed.startsWith('{')) {
    let parsed: any;
    try {
      parsed = JSON.parse(trimmed);
    } catch (e) {
      throw new Error(`Invalid JSON syntax: ${e instanceof Error ? e.message : String(e)}`);
    }

    // Subcase 1a: Full Zook Sector Export Bundle (`{ format: 'zook-sector-v1', config, gridData, empires }`)
    if (parsed.gridData && Array.isArray(parsed.gridData.systems)) {
      const config: SectorHexConfig = {
        ...DEFAULT_SECTOR_CONFIG,
        ...(parsed.config || parsed.gridData.config || {}),
      };
      const gridData: SectorHexGridData = {
        ...parsed.gridData,
        config,
      };
      gridData.systems.forEach((sys) => {
        if (sys.sysResult) sanitizeRealisticSystem(sys.sysResult);
      });
      return {
        sourceFormat: 'stargen-sector',
        config,
        gridData,
        empires: Array.isArray(parsed.empires) ? parsed.empires : undefined,
        activeEmpireId: parsed.activeEmpireId ?? null,
      };
    }

    // Subcase 1b: Direct SectorHexGridData JSON (`{ config, systems, hyperlanes, ... }`)
    if (Array.isArray(parsed.systems) && parsed.config) {
      const config: SectorHexConfig = {
        ...DEFAULT_SECTOR_CONFIG,
        ...parsed.config,
      };
      const gridData: SectorHexGridData = {
        ...parsed,
        config,
      };
      gridData.systems.forEach((sys) => {
        if (sys.sysResult) sanitizeRealisticSystem(sys.sysResult);
      });
      return {
        sourceFormat: 'stargen-sector',
        config,
        gridData,
      };
    }

    // Subcase 1c: SectorHexConfig JSON (`{ seed, columns, rows, density, meanAge, ... }`)
    if (typeof parsed.seed === 'number' && typeof parsed.columns === 'number') {
      const config: SectorHexConfig = {
        ...DEFAULT_SECTOR_CONFIG,
        ...parsed,
      };
      const gridData = generateSectorHexGrid(config);
      return {
        sourceFormat: 'stargen-sector',
        config,
        gridData,
      };
    }

    throw new Error(
      'Unrecognized JSON structure. Expected a Zook Sector JSON file (containing gridData/systems) or Stellaris static_galaxy_scenario (.txt).'
    );
  }

  // Case 2: Stellaris Static Galaxy Scenario Format (`.txt`)
  return parseStellarisStaticGalaxyText(trimmed);
}

/**
 * Parses a Stellaris `static_galaxy_scenario = { ... }` script (or raw `system = { ... }` list)
 * into a complete interactive `SectorHexGridData` with stars, realistic planetary systems, and hyperlanes.
 */
function parseStellarisStaticGalaxyText(text: string): ParsedSectorImportResult {
  // 1. Extract optional top-level Zook metadata comments if present
  const extractCommentNum = (key: string): number | undefined => {
    const m = text.match(new RegExp(`#\\s*${key}\\s*=\\s*([+-]?\\d+(?:\\.\\d+)?)`, 'i'));
    return m ? parseFloat(m[1]) : undefined;
  };
  const extractCommentStr = (key: string): string | undefined => {
    const m = text.match(new RegExp(`#\\s*${key}\\s*=\\s*"([^"]+)"`, 'i'));
    return m ? m[1] : undefined;
  };

  // Extract scenario name (outside `system = { ... }` blocks)
  const headerSlice = text.split(/\bsystem\s*=\s*\{/)[0] || text.slice(0, 1200);
  const scenarioNameMatch = headerSlice.match(/\bname\s*=\s*"([^"]+)"/);
  const scenarioName =
    scenarioNameMatch?.[1] ||
    extractCommentStr('sector_name') ||
    'Imported Stellaris Sector';

  const seed =
    extractCommentNum('sector_seed') ??
    (seedFromId(scenarioName) % 90000) + 1000;
  const columns = Math.max(4, Math.min(100, Math.round(extractCommentNum('columns') ?? 20)));
  const rows = Math.max(4, Math.min(100, Math.round(extractCommentNum('rows') ?? 20)));
  const meanAge = extractCommentNum('mean_age') ?? 4.8;
  const ageSigma = extractCommentNum('age_sigma') ?? 1.8;
  const metallicityMean = extractCommentNum('metallicity_mean') ?? 0.04;
  const metallicitySigma = extractCommentNum('metallicity_sigma') ?? 0.22;
  const coord = extractCommentStr('sector_coord');
  const hasNebulaComment = text.match(/#\s*has_nebula\s*=\s*(yes|true)/i);

  // 2. Extract all `system = { ... }` blocks using balanced brace scanning
  interface RawStellarisSystem {
    stellarisId: string;
    name: string;
    stX: number;
    stY: number;
    hasHomeFlag: boolean;
    spawnWeight: number;
    // Optional Zook round-trip comments inside block
    zookId?: string;
    coord?: string;
    col?: number;
    row?: number;
    pixelX?: number;
    pixelY?: number;
    parsecX?: number;
    parsecY?: number;
    influenceRadius?: number;
    sysMass?: number;
    ageGyr?: number;
    feh?: number;
  }

  const rawSystems: RawStellarisSystem[] = [];
  const sysRegex = /\bsystem\s*=\s*\{/g;
  let match: RegExpExecArray | null;

  while ((match = sysRegex.exec(text)) !== null) {
    const startBraceIdx = match.index + match[0].length - 1;
    let depth = 0;
    let endBraceIdx = startBraceIdx;
    for (let i = startBraceIdx; i < text.length; i++) {
      const ch = text[i];
      if (ch === '{') depth++;
      else if (ch === '}') {
        depth--;
        if (depth === 0) {
          endBraceIdx = i;
          break;
        }
      }
    }
    const block = text.slice(startBraceIdx + 1, endBraceIdx);

    const idMatch = block.match(/\bid\s*=\s*"?([^"\s#}]+)"?/);
    const nameMatch = block.match(/\bname\s*=\s*"([^"]*)"/);
    const posBlockMatch = block.match(/\bposition\s*=\s*\{([^}]*)\}/);
    let stX = 0;
    let stY = 0;
    if (posBlockMatch) {
      const xM = posBlockMatch[1].match(/\bx\s*=\s*([+-]?\d+(?:\.\d+)?)/);
      const yM = posBlockMatch[1].match(/\by\s*=\s*([+-]?\d+(?:\.\d+)?)/);
      if (xM) stX = parseFloat(xM[1]);
      if (yM) stY = parseFloat(yM[1]);
    }

    const zookIdM = block.match(/#\s*zook_id\s*=\s*"([^"]+)"/);
    const coordM = block.match(/#\s*coord\s*=\s*"([^"]+)"/);
    const colM = block.match(/#\s*col\s*=\s*(\d+)/);
    const rowM = block.match(/#\s*row\s*=\s*(\d+)/);
    const pxPosM = block.match(/#\s*pixel_pos\s*=\s*\{\s*x\s*=\s*([+-]?\d+(?:\.\d+)?)\s+y\s*=\s*([+-]?\d+(?:\.\d+)?)\s*\}/);
    const pcPosM = block.match(/#\s*parsec_pos\s*=\s*\{\s*x\s*=\s*([+-]?\d+(?:\.\d+)?)\s+y\s*=\s*([+-]?\d+(?:\.\d+)?)\s*\}/);
    const infRadM = block.match(/#\s*influence_radius\s*=\s*([+-]?\d+(?:\.\d+)?)/);
    const massM = block.match(/#\s*sys_mass_sol\s*=\s*([+-]?\d+(?:\.\d+)?)/);
    const ageM = block.match(/#\s*age_gyr\s*=\s*([+-]?\d+(?:\.\d+)?)/);
    const fehM = block.match(/#\s*metallicity_feh\s*=\s*([+-]?\d+(?:\.\d+)?)/);

    const hasHomeFlag = /empire_home_system/i.test(block);
    const spawnWeightM = block.match(/spawn_weight\s*=\s*\{\s*base\s*=\s*(\d+)/);

    rawSystems.push({
      stellarisId: idMatch ? idMatch[1] : String(rawSystems.length),
      name: nameMatch ? nameMatch[1] : `System ${rawSystems.length + 1}`,
      stX,
      stY,
      hasHomeFlag,
      spawnWeight: spawnWeightM ? parseInt(spawnWeightM[1], 10) : 0,
      zookId: zookIdM?.[1],
      coord: coordM?.[1],
      col: colM ? parseInt(colM[1], 10) : undefined,
      row: rowM ? parseInt(rowM[1], 10) : undefined,
      pixelX: pxPosM ? parseFloat(pxPosM[1]) : undefined,
      pixelY: pxPosM ? parseFloat(pxPosM[2]) : undefined,
      parsecX: pcPosM ? parseFloat(pcPosM[1]) : undefined,
      parsecY: pcPosM ? parseFloat(pcPosM[2]) : undefined,
      influenceRadius: infRadM ? parseFloat(infRadM[1]) : undefined,
      sysMass: massM ? parseFloat(massM[1]) : undefined,
      ageGyr: ageM ? parseFloat(ageM[1]) : undefined,
      feh: fehM ? parseFloat(fehM[1]) : undefined,
    });

    sysRegex.lastIndex = endBraceIdx + 1;
  }

  if (rawSystems.length === 0) {
    throw new Error(
      'No `system = { ... }` blocks found in Stellaris static galaxy text. Check that your file contains valid Stellaris static_galaxy_scenario system entries.'
    );
  }

  // 3. Set up Sector Hex geometry
  const sectorWidth = 2400;
  const sectorHeight = 2400;
  const hexCenterX = 1200;
  const hexCenterY = 1200;
  const hexRadius = 1120;
  const parsecWidth = Math.max(20, columns * 5);
  const parsecHeight = Math.max(20, rows * 5);

  const hexVertices: { x: number; y: number }[] = [];
  const innerPointsArr: string[] = [];
  for (let i = 0; i < 6; i++) {
    const angle = (Math.PI / 180) * (60 * i - 90);
    const vx = +(hexCenterX + hexRadius * Math.cos(angle)).toFixed(1);
    const vy = +(hexCenterY + hexRadius * Math.sin(angle)).toFixed(1);
    hexVertices.push({ x: vx, y: vy });
    const ix = +(hexCenterX + (hexRadius - 35) * Math.cos(angle)).toFixed(1);
    const iy = +(hexCenterY + (hexRadius - 35) * Math.sin(angle)).toFixed(1);
    innerPointsArr.push(`${ix},${iy}`);
  }
  const hexPoints = hexVertices.map((v) => `${v.x},${v.y}`).join(' ');
  const hexInnerPoints = innerPointsArr.join(' ');

  // Normalize external Stellaris coordinates to fit cleanly inside the hexagon if pixel_pos is absent
  let maxExtent = 1;
  rawSystems.forEach((s) => {
    const r = Math.hypot(s.stX, s.stY);
    if (r > maxExtent) maxExtent = r;
  });
  const stScaleToPx = (hexRadius * 0.85) / Math.max(100, maxExtent);

  // 4. Construct SectorHexSystem objects
  const usedCoords = new Set<string>();
  const stellarisIdToSystem = new Map<string, SectorHexSystem>();
  const systems: SectorHexSystem[] = [];

  rawSystems.forEach((raw, idx) => {
    const px =
      raw.pixelX !== undefined
        ? raw.pixelX
        : +(hexCenterX + raw.stX * stScaleToPx).toFixed(1);
    const py =
      raw.pixelY !== undefined
        ? raw.pixelY
        : +(hexCenterY + raw.stY * stScaleToPx).toFixed(1);

    const pcX =
      raw.parsecX !== undefined
        ? raw.parsecX
        : +((px / sectorWidth) * parsecWidth).toFixed(1);
    const pcY =
      raw.parsecY !== undefined
        ? raw.parsecY
        : +((py / sectorHeight) * parsecHeight).toFixed(1);

    let col =
      raw.col ??
      Math.max(1, Math.min(columns, Math.ceil((px / sectorWidth) * columns)));
    let row =
      raw.row ??
      Math.max(1, Math.min(rows, Math.ceil((py / sectorHeight) * rows)));
    let hexCoord = raw.coord || formatHexCoord(col, row);

    // Ensure unique coord if multiple stars map to same cell
    let attempt = 0;
    while (usedCoords.has(hexCoord) && attempt < 200) {
      attempt++;
      col = ((col + attempt - 1) % columns) + 1;
      if (attempt % columns === 0) {
        row = (row % rows) + 1;
      }
      hexCoord = formatHexCoord(col, row);
    }
    usedCoords.add(hexCoord);

    const sysId =
      raw.zookId ||
      `SYS-${hexCoord}-${(seedFromId(`${raw.stellarisId}_${raw.name}_${seed}`) % 9000) + 1000}`;

    const rng = new PRNG(seedFromId(sysId));
    const sysMass =
      raw.sysMass !== undefined
        ? raw.sysMass
        : raw.hasHomeFlag || raw.spawnWeight >= 50
        ? +(0.82 + rng.next() * 0.42).toFixed(3) // Sun-like G/K star for homeworld systems
        : +(0.18 + Math.pow(rng.next(), 1.6) * 2.4).toFixed(3);
    const sysAge =
      raw.ageGyr !== undefined
        ? raw.ageGyr
        : +(Math.max(0.3, Math.min(12.2, meanAge + (rng.next() - 0.5) * ageSigma * 2))).toFixed(2);
    const sysFeh =
      raw.feh !== undefined
        ? raw.feh
        : +(Math.max(-1.5, Math.min(0.45, metallicityMean + (rng.next() - 0.5) * metallicitySigma * 2))).toFixed(2);

    const sysResult = runRealisticGenerator({
      sysMass,
      age: sysAge,
      feh: sysFeh,
      id: sysId,
      name: raw.name,
      forcedMult: 'auto',
    });

    const starA = sysResult.hierarchy.stars[0];
    const isRemnant = starA.category.toLowerCase().includes('remnant');
    const spectralCat = classifySpectralCatFromType(starA.spectralType, isRemnant);

    let planetCount = 0;
    let beltCount = 0;
    let habitableWorldCount = 0;
    const habitableTypes: string[] = [];

    sysResult.zones.forEach((z) => {
      z.bodies.forEach((b) => {
        if (b.kind === 'belt') {
          beltCount++;
        } else {
          planetCount++;
          if (
            b.hydrosphere &&
            (b.hydrosphere.state.includes('Liquid') ||
              (b.hydrosphere.biosphere && b.hydrosphere.biosphere !== 'none'))
          ) {
            habitableWorldCount++;
            habitableTypes.push(b.planetClass);
          }
          (b.moons || []).forEach((m) => {
            if (
              m.hydrosphere &&
              (m.hydrosphere.state.includes('Liquid') ||
                (m.hydrosphere.biosphere && m.hydrosphere.biosphere !== 'none'))
            ) {
              habitableWorldCount++;
              habitableTypes.push(m.moonClass);
            }
          });
        }
      });
    });

    const hexSys: SectorHexSystem = {
      age: sysAge,
      mass: sysMass,
      metallicity: sysFeh,
      id: sysId,
      x: px,
      y: py,
      influenceRadius: raw.influenceRadius ?? 32,
      parsecX: pcX,
      parsecY: pcY,
      name: raw.name || `System ${idx + 1}`,
      col,
      row,
      coord: hexCoord,
      primaryClass: starA.spectralType,
      primaryMass: starA.mass,
      spectralCat,
      colorHex: starA.colorHex,
      glowColor: starA.colorHex,
      teff: starA.Teff,
      lumLsun: starA.lumNum,
      isRemnant,
      remnantType: isRemnant ? starA.spectralType : null,
      nStars: sysResult.hierarchy.stars.length,
      archName: sysResult.hierarchy.archName,
      companionStars: sysResult.hierarchy.stars.slice(1),
      planetCount,
      beltCount,
      candidateHabitable: habitableWorldCount > 0,
      habitableWorldCount,
      habitableTypes,
      isGiantSystem: sysMass >= 10,
      sysResult,
    };

    systems.push(hexSys);
    stellarisIdToSystem.set(raw.stellarisId, hexSys);
  });

  // 5. Extract all `add_hyperlane = { from = "..." to = "..." }` blocks
  const hyperlanes: SectorHyperlane[] = [];
  const hlRegex = /\badd_hyperlane\s*=\s*\{([^}]*)\}/g;
  let hlMatch: RegExpExecArray | null;
  while ((hlMatch = hlRegex.exec(text)) !== null) {
    const body = hlMatch[1];
    const fromM = body.match(/\bfrom\s*=\s*"?([^"\s#}]+)"?/);
    const toM = body.match(/\bto\s*=\s*"?([^"\s#}]+)"?/);
    if (!fromM || !toM) continue;
    const srcSys = stellarisIdToSystem.get(fromM[1]);
    const tgtSys = stellarisIdToSystem.get(toM[1]);
    if (!srcSys || !tgtSys || srcSys.id === tgtSys.id) continue;

    const lengthPx = +Math.hypot(tgtSys.x - srcSys.x, tgtSys.y - srcSys.y).toFixed(1);
    const lengthPc = Math.hypot(tgtSys.parsecX - srcSys.parsecX, tgtSys.parsecY - srcSys.parsecY);
    const lengthLy = +(lengthPc * 3.26156).toFixed(1);

    hyperlanes.push({
      id: `HL-${srcSys.id}__${tgtSys.id}`,
      sourceId: srcSys.id,
      targetId: tgtSys.id,
      sourceCoord: srcSys.coord,
      targetCoord: tgtSys.coord,
      x1: srcSys.x,
      y1: srcSys.y,
      x2: tgtSys.x,
      y2: tgtSys.y,
      lengthPx,
      lengthLy,
      isEdgeLane: false,
    });
  }

  // 6. Check for active `nebula = { ... }` blocks (uncommented)
  const uncommentedLines = text
    .split('\n')
    .map((l) => l.replace(/#.*$/, ''))
    .join('\n');
  const nebulaMatch = uncommentedLines.match(/\bnebula\s*=\s*\{([^}]*)\}/);
  const hasNebula = Boolean(hasNebulaComment || nebulaMatch);
  let nebula: SectorNebula | null = null;
  if (hasNebula) {
    const nebNameMatch = nebulaMatch?.[1]?.match(/\bname\s*=\s*"([^"]+)"/);
    nebula = {
      name: nebNameMatch?.[1] || `${scenarioName} Nebula`,
      type: 'H II Emission Nursery',
      description: 'Imported interstellar emission nebula complex.',
      blobs: [
        {
          cx: hexCenterX,
          cy: hexCenterY,
          rx: 520,
          ry: 380,
          rotation: 28,
          coreColor: '#f43f5e',
          midColor: '#a855f7',
          opacity: 0.42,
        },
      ],
      dustLanes: [],
    };
  }

  // 7. Build cells and stats
  const sysByCoord = new Map<string, SectorHexSystem>();
  systems.forEach((s) => sysByCoord.set(s.coord, s));
  const cells: SectorHexCell[] = [];
  for (let r = 1; r <= rows; r++) {
    for (let c = 1; c <= columns; c++) {
      const cellCoord = formatHexCoord(c, r);
      cells.push({
        col: c,
        row: r,
        coord: cellCoord,
        system: sysByCoord.get(cellCoord) || null,
      });
    }
  }

  const totalHexes = columns * rows;
  const occupiedHexes = systems.length;
  const density = +(occupiedHexes / Math.max(1, totalHexes)).toFixed(2);

  const config: SectorHexConfig = {
    seed,
    name: scenarioName,
    coord,
    columns,
    rows,
    density: Math.max(0.05, Math.min(3.5, extractCommentNum('density') ?? density)),
    meanAge,
    ageSigma,
    metallicityMean,
    metallicitySigma,
    hasNebula,
  };

  let obCount = 0;
  let afCount = 0;
  let gCount = 0;
  let kmCount = 0;
  let remnantCount = 0;
  let multipleSystemCount = 0;
  let heavyMassCount = 0;
  let giantCount = 0;
  let habitableCount = 0;
  let nonMsCount = 0;
  let totalStars = 0;

  systems.forEach((s) => {
    totalStars += s.nStars;
    if (s.spectralCat === 'ob') obCount++;
    else if (s.spectralCat === 'af') afCount++;
    else if (s.spectralCat === 'g') gCount++;
    else if (s.spectralCat === 'km') kmCount++;
    else if (s.spectralCat === 'remnant') remnantCount++;
    if (s.nStars > 1) multipleSystemCount++;
    if (s.mass >= 3.0) heavyMassCount++;
    if (s.isGiantSystem) giantCount++;
    if (s.candidateHabitable) habitableCount++;
    if (s.isRemnant || !s.primaryClass.endsWith('V')) nonMsCount++;
  });

  const gridData: SectorHexGridData = {
    config,
    sectorWidth,
    sectorHeight,
    parsecWidth,
    parsecHeight,
    cells,
    systems,
    hyperlanes,
    integratedColorHex: extractCommentStr('integrated_color_hex') || '#38bdf8',
    hasNebula,
    nebula,
    hexRadius,
    hexCenterX,
    hexCenterY,
    hexPoints,
    hexInnerPoints,
    hexVertices,
    stats: {
      totalHexes,
      occupiedHexes,
      occupancyPct: Math.round((occupiedHexes / Math.max(1, totalHexes)) * 100),
      totalStars,
      hyperlaneCount: hyperlanes.length,
      obCount,
      afCount,
      gCount,
      kmCount,
      remnantCount,
      multipleSystemCount,
      heavyMassCount,
      giantCount,
      habitableCount,
      nonMsCount,
    },
  };

  return {
    sourceFormat: 'stellaris-static-galaxy',
    config,
    gridData,
  };
}
